"""Входной файл для NiceGUI-симулятора в тестах.

Симулятор импортирует этот модуль как «главный» и поднимает приложение.
`ui.run()` обязателен: без него NiceGUI считает, что сервер не запущен.

* `reload=False` — иначе симулятор откажется работать с пакетом `python -m`;
* `show=False` — не пытаться открыть окно браузера в CI;
* порт 0 — свободный порт, чтобы тесты не конфликтовали.

Страницы, которые проверяет тест, регистрируются в самом тесте.
"""

from nicegui import ui

if __name__ in {"__main__", "__mp_main__"}:
    ui.run(port=0, reload=False, show=False)
