# Группа контейнеров отображается отдельно, но хранится в общей таблице.
CONTAINER_KINDS = {"PARTICIPANT", "LANE"}


def group_of(kind: str) -> str:
    info = CATALOG.get(kind)
    if info is None:
        return ""
    if kind in CONTAINER_KINDS:
        return "Контейнеры"
    return info["group"]


def label_of(kind: str, name: str | None = None) -> str:
    """Подпись для палитры: пользовательское имя, если оно задано и отличается."""
    info = CATALOG.get(kind) or {}
    default = info.get("label", kind)
    if name and name not in {kind, default}:
        return name
    return default


def by_groups() -> list[tuple[str, list[tuple[str, str]]]]:
    """Символы, разложенные по группам и в порядке отображения."""
    result: list[tuple[str, list[tuple[str, str]]]] = []
    for group in (*GROUP_ORDER, "Контейнеры"):
        items = [
            (kind, info["label"])
            for kind, info in CATALOG.items()
            if group_of(kind) == group
        ]
        if items:
            result.append((group, items))
    return result


def same_semantics(old_kind: str, new_kind: str) -> bool:
    """Совместимость кодов: старые диаграммы открываются без миграции."""
    return old_kind == new_kind
